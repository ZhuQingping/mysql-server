bool CdeIsDdlLogDisable(THD *thd);

/**
Whether current thd is executing a DDL command and with a read write
transacion of Dstore.

@param[in]  thd    Pointer of session descriptor.

@return true if thd is executing a DDL command and with a read write
             transacion of Dstore, otherwise false.
*/
bool CdeIsDdlWithTrx(THD *thd);

inline bool CdeIsDdlLogTableName(const char *name) {
  const char *ddlLogTable = "./mysql/dstore_ddl_log";
  if (strlen(name) == strlen(ddlLogTable) &&
      strncmp(name, ddlLogTable, strlen(ddlLogTable)) == 0) {
    return true;
  }
  return false;
}

